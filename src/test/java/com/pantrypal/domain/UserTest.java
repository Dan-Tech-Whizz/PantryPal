package com.pantrypal.domain;

import static org.junit.jupiter.api.Assertions.*;
import com.pantrypal.model.PantryItem;
import com.pantrypal.model.User;
import com.pantrypal.support.TestLogger;
import java.time.LocalDate;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;

@ExtendWith(TestLogger.class)
class UserTest {

    private static PantryItem milk() {
        return new PantryItem(LocalDate.of(2026, 10, 5), LocalDate.of(2026,
                10, 12), 2);
    }

    @Test
    void newUserHasDefaultSettings() {
        User user = new User("Daniel Wright", "daniel@pantrypal.test",
                "secret-hash");
        assertNull(user.getId(), "id is generated by the database, not the constructor");
        assertEquals("Daniel Wright", user.getName());
        assertEquals("daniel@pantrypal.test", user.getEmail());
        assertTrue(user.getNotificationsEnabled());
        assertFalse(user.getAllowPurchaseSuggestions());
        assertTrue(user.getPantryItems().isEmpty());
    }

    @Test
    void settersChangeTheSettings() {
        User user = new User("A", "a@pantrypal.test", "h");
        user.setNotificationsEnabled(false);
        user.setAllowPurchaseSuggestions(true);
        assertFalse(user.getNotificationsEnabled());
        assertTrue(user.getAllowPurchaseSuggestions());
    }

    @Test
    void addPantryItemKeepsBothSidesInSync() {
        User user = new User("A", "a@pantrypal.test", "h");
        PantryItem item = milk();
        user.addPantryItem(item);
        assertEquals(1, user.getPantryItems().size());
        assertSame(user, item.getUser(), "the back-reference fills the foreign key");
    }

    @Test
    void removePantryItemClearsTheBackReference() {
        User user = new User("A", "a@pantrypal.test", "h");
        PantryItem item = milk();
        user.addPantryItem(item);
        user.removePantryItem(item);
        assertTrue(user.getPantryItems().isEmpty());
        assertNull(item.getUser());
    }

    @Test
    void toStringHidesThePasswordHashAndTheItems() {
        User user = new User("Daniel", "daniel@pantrypal.test", "secrethash");
        user.addPantryItem(milk());
        String text = user.toString();
        assertTrue(text.contains("daniel@pantrypal.test"));
        assertFalse(text.contains("secret-hash"), "never print the password hash");
        assertFalse(text.contains("PantryItem"), "printing a lazy collection can loop or fail");
    }
}
